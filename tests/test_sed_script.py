"""The file names a GNU sed script writes by itself, as pure text reading.
Every row's expectation was measured against GNU sed 4.9: the files it opened
for writing (created or truncated) running the pieces as `-e` values."""

from __future__ import annotations

import pytest

from agent_coordination.sed_script import sed_script_write_targets


@pytest.mark.parametrize(
    ("pieces", "targets"),
    [
        # a write command's name runs from its first non-blank to the line end
        (("w x",), (("x", 0),)),
        (("W x",), (("x", 0),)),
        (("s/a/b/w x",), (("x", 0),)),
        (("w x\nw y",), (("x", 0), ("y", 0))),
        (("w x;p",), (("x;p", 0),)),
        (("w x ",), (("x ", 0),)),
        (("w   x",), (("x", 0),)),
        (("w\tx",), (("x", 0),)),
        # a write without a name is a GNU error
        (("w",), ()),
        (("w ",), ()),
        (("s/a/b/w",), ()),
        (("s/a/b/w", "x"), ()),
        # GNU skips carriage return, vertical tab and form feed between commands
        (("\rw x",), (("x", 0),)),
        (("p;\x0bw x",), (("x", 0),)),
        (("\x0cw x",), (("x", 0),)),
        (("s/a/b/\r\nw x",), (("x", 0),)),
        (("{\rw x\n}",), (("x", 0),)),
        (("{\x0bw x\n}",), (("x", 0),)),
        (("{\x0cw x\n}",), (("x", 0),)),
        (("w x\r",), (("x\r", 0),)),
        # inside a command only blank and tab are blanks
        (("p\rw x",), ()),
        (("1\rw x",), ()),
        (("{p}\rw x",), ()),
        (("s/a/b/\rw x",), ()),
        # every address form, with any delimiter
        (("1w x",), (("x", 0),)),
        (("$w x",), (("x", 0),)),
        (("1~2w x",), (("x", 0),)),
        (("0~4w x",), (("x", 0),)),
        (("/a/w x",), (("x", 0),)),
        (("/a/Iw x",), (("x", 0),)),
        (("/a/IMw x",), (("x", 0),)),
        (("\\,a,w x",), (("x", 0),)),
        (("1,3w x",), (("x", 0),)),
        (("1,+2w x",), (("x", 0),)),
        (("1,~2w x",), (("x", 0),)),
        (("/a/,/b/w x",), (("x", 0),)),
        (("1 , 3 w x",), (("x", 0),)),
        (("1!w x",), (("x", 0),)),
        (("1 ! w x",), (("x", 0),)),
        (("!w x",), (("x", 0),)),
        (("1,$!w x",), (("x", 0),)),
        (("\\\\a\\w x",), (("x", 0),)),
        (("s\\a\\b\\w x",), (("x", 0),)),
        # a + or ~ first address consumes its digits: GNU rejects most numbers but
        # accepts a multiple of 2^64, which it wraps to zero
        (("+w x",), (("x", 0),)),
        (("~w x",), (("x", 0),)),
        (("+0w x",), (("x", 0),)),
        (("~0w x",), (("x", 0),)),
        (("+!w x",), (("x", 0),)),
        (("+ w x",), (("x", 0),)),
        (("+0,3w x",), (("x", 0),)),
        (("+p;w x",), (("x", 0),)),
        (("+18446744073709551616w x",), (("x", 0),)),
        (("~18446744073709551616w x",), (("x", 0),)),
        (("+36893488147419103232w x",), (("x", 0),)),
        (("+18446744073709551616p;w x",), (("x", 0),)),
        (("+1w x",), (("x", 0),)),  # GNU rejects; sentence 6 false alarm
        (("~2w x",), (("x", 0),)),  # GNU rejects; sentence 6 false alarm
        (("+ 2w x",), (("x", 0),)),  # GNU rejects; sentence 6 false alarm
        # blanks around the address flags and the step of first~step
        (("/b/ Iw x",), (("x", 0),)),
        (("/b/ I w x",), (("x", 0),)),
        (("\\,b, I w x",), (("x", 0),)),
        (("/b/I,/c/ Mw x",), (("x", 0),)),
        (("/a/I M w x",), (("x", 0),)),
        (("/a/I \tMw x",), (("x", 0),)),
        (("/a/\tIw x",), (("x", 0),)),
        (("1 ~2w x",), (("x", 0),)),
        (("1~ 2w x",), (("x", 0),)),
        (("1 ~ 2w x",), (("x", 0),)),
        (("10 ~W x",), (("x", 0),)),
        (("1,2 ~3w x",), (("x", 0),)),
        (("1~ w x",), (("x", 0),)),
        (("1~0w x",), (("x", 0),)),
        (("1,+ 2w x",), (("x", 0),)),
        (("1,~ 2w x",), (("x", 0),)),
        (("1 , + 2 w x",), (("x", 0),)),
        (("1,+\t2w x",), (("x", 0),)),
        (("1\t~2w x",), (("x", 0),)),
        (("/a/ , /b/ w x",), (("x", 0),)),
        (("0,/a/ Iw x",), (("x", 0),)),
        (("2 ! w x",), (("x", 0),)),
        (("1,+w x",), (("x", 0),)),
        (("1,~w x",), (("x", 0),)),
        (("$ ~2w x",), ()),
        (("1\n~2w x",), ()),
        (("1~\n2w x",), ()),
        (("1,+\n2w x",), ()),
        (("/a/\nIw x",), ()),
        (("/a/I\nM w x",), ()),
        # brackets and backslashes inside a pattern hide the delimiter
        (("/[/]/w x",), (("x", 0),)),
        (("s/[/]/x/w x",), (("x", 0),)),
        (("/[]/]/w x",), (("x", 0),)),
        (("/[^]/]/w x",), (("x", 0),)),
        (("/[[:alpha:]/]/w x",), (("x", 0),)),
        (("s/a/[/w x",), (("x", 0),)),
        (("y/[/]/\nw x",), (("x", 0),)),
        (("/a\\/b/w x",), (("x", 0),)),
        (("s/a\\/b/c/w x",), (("x", 0),)),
        # a, i, c and e text holds no command
        (("a w x",), ()),
        (("a\\\nw x",), ()),
        (("a foo\nw x",), (("x", 0),)),
        (("a\nw x",), (("x", 0),)),
        (("a\\ \nw x",), (("x", 0),)),
        (("a\\\\\nw x",), (("x", 0),)),
        (("a\\ \\\nw x",), ()),
        (("a\\\\\\\nw x",), ()),
        (("a foo\\\nw x",), ()),
        (("i\\ \nw x",), (("x", 0),)),
        (("c\\\\\nw x",), (("x", 0),)),
        (("e\\ \nw x",), (("x", 0),)),
        (("e\nw x",), (("x", 0),)),
        (("a",), ()),
        (("a\\", "w x"), ()),
        (("e\\", "w x"), ()),
        # labels and numbers before the next command
        (("b a\rw x",), ()),
        (("b a w x",), (("x", 0),)),
        (("ba;w x",), (("x", 0),)),
        (("{b a}\nw x",), (("x", 0),)),
        ((":a;w x",), (("x", 0),)),
        (("t;w x",), (("x", 0),)),
        (("T a;w x",), (("x", 0),)),
        (("v;w x",), (("x", 0),)),
        (("l 5;w x",), (("x", 0),)),
        (("q5\nw x",), (("x", 0),)),
        (("Q;w x",), (("x", 0),)),
        (("l\rw x",), ()),
        # the s flags up to the write flag
        (("s/a/b/gpw x",), (("x", 0),)),
        (("s/a/b/ w x",), (("x", 0),)),
        (("s/a/b/ggw x",), ()),
        (("s/a/b/2 3w x",), ()),
        (("s/a/b/0w x",), ()),
        (("s/a/b/" + "0" * 4300 + "w x",), ()),
        (("s/a/b/" + "0" * 4300 + "1w x",), (("x", 0),)),
        (("s/a/b/ppw x",), ()),
        (("s/a/b/2gw x",), (("x", 0),)),
        (("s/a/b/Iw x",), (("x", 0),)),
        (("s/a/b/xw y",), ()),
        (("s/a/b/;w x",), (("x", 0),)),
        (("s/a/b/#c\nw x",), (("x", 0),)),
        (("s/a/b/\nw x",), (("x", 0),)),
        (("s,a,b,w x",), (("x", 0),)),
        (("s/a/b",), ()),
        (("s/a\nb/c/w x",), ()),
        (("s/a/b\nc/w x",), ()),
        (("s/a/b/²w x",), ()),
        # commands that write no file
        (("#w x",), ()),
        (("p # w x\nw y",), (("y", 0),)),
        (("y/w/x/",), ()),
        (("s/a/w x/",), ()),
        (("/w x/p",), ()),
        (("r w x",), ()),
        (("R w x",), ()),
        (("r w x\nw y",), (("y", 0),)),
        # reading stops at the first construct GNU rejects
        (("w y\nk\nw x",), (("y", 0),)),
        (("w y\np p\nw x",), (("y", 0),)),
        (("w y\ns/a/b/ggw z",), (("y", 0),)),
        (("e",), ()),
        (("w y\ne",), (("y", 0),)),
        (("s",), ()),
        (("y\nw x",), ()),
        (("w y\n/[a",), (("y", 0),)),
        (("w y\n/[a\n]/w x",), (("y", 0),)),
        (("w y\n/[[:alpha",), (("y", 0),)),
        (("w y\n1,w x",), (("y", 0),)),
        # pieces are one script joined by a line end
        (("p", "\rw x"), (("x", 1),)),
        (("w x", "w y"), (("x", 0), ("y", 1))),
        (("", "w x"), (("x", 1),)),
        ((), ()),
        (("p\nw x", "w y"), (("x", 0), ("y", 1))),
    ],
    ids=repr,
)
def test_sed_script_write_targets_name_the_files_gnu_sed_opens_for_writing(
    pieces: tuple[str, ...], targets: tuple[tuple[str, int], ...]
) -> None:
    assert sed_script_write_targets(pieces) == targets
